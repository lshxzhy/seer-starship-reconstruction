// Skills can carry several effects in one flat argument list. Always advance by
// the client's arity, including when the effect has no local implementation.
function decodeSpiritEffects(row){
  const codes=row[9]||[],values=row[10]||[],parts=[];
  let offset=0;
  for(const code of codes){
    const width=SPIRIT_EFFECT_ARITY[code];
    if(!(width>=0)||offset+width>values.length){
      parts.push({code,args:null});offset=null;break;
    }
    parts.push({code,args:values.slice(offset,offset+width)});offset+=width;
  }
  if(offset!==null&&offset<values.length){
    // Some old stat moves list a single effect ID followed by several stat triples.
    if(codes.length===1&&(codes[0]===4||codes[0]===5)&&(values.length-offset)%3===0){
      for(;offset<values.length;offset+=3)parts.push({code:codes[0],args:values.slice(offset,offset+3)});
    }else parts.push({code:null,args:null});
  }
  return parts;
}

